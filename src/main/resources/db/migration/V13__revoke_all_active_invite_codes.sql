-- 1일 만료"로 바꾸면서, 배포 시점에 이미 발급돼 있던 코드도 즉시 새 정책을 적용받도록
-- 전부 폐기한다. 하드 삭제가 아니라 revoke만 하므로, 그 코드로 합류한 이력
-- (team_members.joined_via_invite_id)은 그대로 보존된다.
--
-- 이 마이그레이션 직후 다음 "초대 코드 발급" 호출 시점에 각 팀마다 새 코드(1일 만료)가
-- 발급된다. 그 순간 기존에 공유돼 있던 옛 코드는 즉시 무효화된다.
--
-- V11 이전 해시 저장 방식에서 넘어와 invite_code가 NULL인 레거시 행도 이 조건
-- (revoked_at IS NULL)에 해당하므로 함께 폐기된다.
-- ============================================================

UPDATE team_invite_links
SET revoked_at = NOW(3)
WHERE revoked_at IS NULL;
